"""Run and report the WP5 evaluation of the prescriptive layer (RQ3).

    PYTHONPATH=src python scripts/run_prescription_benchmark.py run tuning main --workers 4 \\
        --cache-dir /path/to/cache
    PYTHONPATH=src python scripts/run_prescription_benchmark.py report --cache-dir ... \\
        --out docs/evidence/wp5

``run`` computes every run of the named experiments that is not cached yet (one JSON file
per run in the cache); ``report`` reads the cache and writes Markdown tables and a JSON
summary. Experiments: ``tuning`` (thermocouple-check thresholds on tuning seeds), ``main``
(19 scenarios x 3 modes x 5 test seeds), ``delay``, ``mismatch``, ``objective`` and
``wash``. See ``turbineiq.prescription.evaluation`` and ``docs/WP5_RESULTS.md``.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import time
from pathlib import Path

from turbineiq.prescription import evaluation as ev


def _git_commit() -> str | None:
    try:
        out = subprocess.run(
            ["git", "rev-parse", "HEAD"], capture_output=True, text=True, check=True, timeout=10
        )
    except (OSError, subprocess.SubprocessError):
        return None
    return out.stdout.strip() or None


def _run(names: list[str], cache_dir: Path, workers: int) -> None:
    for name in names:
        specs = ev.EXPERIMENTS[name]()
        print(f"== {name}: {len(set(specs))} runs", flush=True)
        stats = ev.ensure_results(specs, cache_dir, workers=workers)
        print(f"== {name}: {stats}", flush=True)


def _report(cache_dir: Path, out: Path, names: list[str]) -> None:
    out.mkdir(parents=True, exist_ok=True)
    summary: dict = {
        "commit": _git_commit(),
        "code_fingerprint": ev.code_fingerprint(),
        "test_seeds": list(ev.TEST_SEEDS),
        "tuning_seeds": list(ev.TUNING_SEEDS),
        "secondary_seeds": list(ev.SECONDARY_SEEDS),
        "generated": time.strftime("%Y-%m-%d %H:%M:%S"),
    }
    md: list[str] = []
    walls = {}
    if "tuning" in names:
        res = ev.load_results(ev.tuning_specs(), cache_dir)
        rows = ev.false_positive_summary(res)
        summary["tuning"] = {"runs": len(res), "rows": rows}
        walls["tuning"] = sum(r["wall_s"] for r in res)
        md.append("## Thermocouple check on tuning seeds\n")
        md.append(ev.markdown_false_positives(rows))
    if "main" in names:
        res = ev.load_results(ev.main_specs(), cache_dir)
        s = ev.summarise_main(res)
        s["runs"] = len(res)
        s["table"] = ev.scenario_mode_table(res)
        s["false_positives"] = ev.false_positive_summary(res)
        summary["main"] = s
        walls["main"] = sum(r["wall_s"] for r in res)
        md.append(ev.markdown_main(s, s["table"]))
        md.append("\n### Thermocouple check on test seeds (all scenarios)\n")
        md.append(ev.markdown_false_positives(s["false_positives"]))
    for name in ("delay", "mismatch", "objective"):
        if name not in names:
            continue
        specs = getattr(ev, f"{name}_specs")()
        res = ev.load_results(specs, cache_dir)
        base = ev.load_results(ev.manual_baselines(specs), cache_dir)
        rows = ev.summarise_secondary(name, res, base)
        summary[name] = {"runs": len(res), "rows": rows}
        walls[name] = sum(r["wall_s"] for r in res)
        md.append(f"\n## Secondary experiment: {name}\n")
        md.append(ev.markdown_secondary(name, rows))
    if "wash" in names:
        res = ev.load_results(ev.wash_specs(), cache_dir)
        s = ev.summarise_wash(res)
        summary["wash"] = s
        walls["wash"] = sum(r["wall_s"] for r in res)
        md.append("\n## Secondary experiment: wash timing\n")
        md.append(ev.markdown_wash(s))
    summary["cpu_s_per_experiment"] = walls
    (out / "benchmark_summary.json").write_text(json.dumps(summary, indent=1, default=str) + "\n")
    header = (
        "# WP5 evaluation tables\n\nGenerated by `scripts/run_prescription_benchmark.py report` "
        f"at commit `{summary['commit']}` (code fingerprint `{summary['code_fingerprint'][:12]}`)."
        " Write-up: `docs/WP5_RESULTS.md`.\n\n"
    )
    (out / "benchmark.md").write_text(header + "\n".join(md))
    print(f"wrote {out / 'benchmark.md'} and {out / 'benchmark_summary.json'}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("action", choices=("run", "report"))
    parser.add_argument("experiments", nargs="*", default=list(ev.EXPERIMENTS))
    parser.add_argument("--cache-dir", type=Path, default=ev.DEFAULT_CACHE_DIR)
    parser.add_argument("--workers", type=int, default=4)
    parser.add_argument("--out", type=Path, default=Path("docs/evidence/wp5"))
    args = parser.parse_args(argv)
    bad = [n for n in args.experiments if n not in ev.EXPERIMENTS]
    if bad:
        parser.error(f"unknown experiments {bad}; choose from {list(ev.EXPERIMENTS)}")
    if args.action == "run":
        _run(args.experiments, args.cache_dir, args.workers)
    else:
        _report(args.cache_dir, args.out, args.experiments)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
